/**
 * Helper to retrieve requirements schema for any template.
 * If templateId is not found, falls back safely to 'modern-academic'.
 */
export function getTemplateRequirements(templateId: string): TemplateRequirementsSchema {
  if (TEMPLATE_REQUIREMENTS[templateId]) {
    return TEMPLATE_REQUIREMENTS[templateId];
  }
  return TEMPLATE_REQUIREMENTS['modern-academic'];
}

/**
 * Retrieves the level definition for a given template and levelId.
 */
export function getSubtypeLevel(
  templateId: string,
  levelId?: string
): CardSubtypeLevel | undefined {
  const schema = getTemplateRequirements(templateId);
  if (!schema.levels || schema.levels.length === 0) return undefined;
  if (!levelId) {
    return schema.levels.find((l) => l.id === schema.defaultLevelId) || schema.levels[0];
  }
  return schema.levels.find((l) => l.id === levelId) || schema.levels[0];
}
